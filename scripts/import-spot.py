#!/usr/bin/env python3
"""Pack pinned Menagerie Spot OBJs without simplifying or changing their shape.
Usage: python scripts/import-spot.py /path/to/spot-source
Source directory contains spot.xml, LICENSE, README.md, commit.txt and assets/*.obj.
"""
import sys,pathlib,json,xml.etree.ElementTree as ET,struct,gzip,hashlib,math,itertools,shutil
src=pathlib.Path(sys.argv[1]);out=pathlib.Path(__file__).resolve().parents[1]/'assets/spot';out.mkdir(exist_ok=True)
root=ET.parse(src/'spot.xml').getroot();commit=(src/'commit.txt').read_text().strip()
conv=lambda p:[p[0],p[2],-p[1]]
nums=lambda s:list(map(float,s.split()))
def qrot(v,q):
 w,x,y,z=q;n=math.sqrt(sum(a*a for a in q));w,x,y,z=[a/n for a in q];t=[2*(y*v[2]-z*v[1]),2*(z*v[0]-x*v[2]),2*(x*v[1]-y*v[0])];return [v[0]+w*t[0]+y*t[2]-z*t[1],v[1]+w*t[1]+z*t[0]-x*t[2],v[2]+w*t[2]+x*t[1]-y*t[0]]
def inertial(node):
 a=node.find('inertial').attrib;diag=nums(a['diaginertia']);basis=[conv(qrot(v,nums(a.get('quat','1 0 0 0')))) for v in [[1,0,0],[0,1,0],[0,0,1]]];tensor=[[sum(diag[k]*basis[k][i]*basis[k][j] for k in range(3)) for j in range(3)] for i in range(3)];return {'mass':float(a['mass']),'pos':conv(nums(a['pos'])),'tensor':tensor}
def obj(name):
 v=[];n=[];f=[]
 for line in (src/'assets'/name).read_text().splitlines():
  if line.startswith('v '):v.append(conv(nums(line[2:])))
  elif line.startswith('vn '):n.append(conv(nums(line[3:])))
  elif line.startswith('f '):
   face=[tuple(int(x) if x else 0 for x in a.split('/')) for a in line[2:].split()]
   for j in range(1,len(face)-1):f.extend([face[0],face[j],face[j+1]])
 return v,n,f
visuals=[];nodes=[]
def node(body,parent=None):
 name=body.get('name');entry={'name':name,'parent':parent,'pos':conv(nums(body.get('pos','0 0 0'))),'inertial':inertial(body),'visuals':[]}
 if parent is None:entry['pos']=[0,0,0]
 joint=body.find('joint')
 if joint is not None:entry['joint']={'name':joint.get('name'),'axis':conv(nums(joint.get('axis','0 0 1'))),'range':nums(joint.get('range'))}
 for g in body.findall('geom'):
  if g.get('class')=='visual':
   entry['visuals'].append({'mesh':g.get('mesh'),'material':g.get('material')});visuals.append(g.get('mesh'))
  elif g.get('class')=='collision':entry['collision']=g.get('mesh')
 nodes.append(entry)
 for child in body.findall('body'):node(child,name)
node(root.find('worldbody/body'))
blob=bytearray();manifest={}
for name in dict.fromkeys(visuals):
 v,n,f=obj(name+'.obj');positions=[];normals=[];indices=[];lookup={}
 for key in f:
  if key not in lookup:
   lookup[key]=len(positions)//3;positions.extend(v[key[0]-1]);normals.extend(n[key[2]-1] if len(key)>2 and key[2] else [0,0,0])
  indices.append(lookup[key])
 offset=len(blob);blob.extend(struct.pack('<%sf'%len(positions),*positions));blob.extend(struct.pack('<%sf'%len(normals),*normals));blob.extend(struct.pack('<%sI'%len(indices),*indices));manifest[name]={'offset':offset,'vertices':len(positions)//3,'indices':len(indices),'sourceSha256':hashlib.sha256((src/'assets'/(name+'.obj')).read_bytes()).hexdigest()}
 print(name,len(positions)//3,len(indices)//3)
(out/'meshes.bin.gz').write_bytes(gzip.compress(blob,compresslevel=9,mtime=0))
materials={m.get('name'):nums(m.get('rgba')) for m in root.findall('asset/material')}
# Physical support approximation: support vertices of the original collision hulls.
# Keep every source vertex too, for provenance and geometry/ground validation.
collisions={};directions=[p for p in itertools.product([-1,0,1],repeat=3) if any(p)]
for name in dict.fromkeys(n.get('collision') for n in nodes if n.get('collision')):
 raw,_,faces=obj(name+'.obj');v=list(dict.fromkeys(tuple(p) for p in raw));lookup={p:i for i,p in enumerate(v)};triangles=[lookup[tuple(raw[f[0]-1])] for f in faces];support=[]
 for d in directions:
  pt=max(v,key=lambda p:sum(a*b for a,b in zip(p,d)))
  if pt not in support:support.append(pt)
 collisions[name]={'vertices':v,'triangles':triangles,'support':support,'bounds':[[min(p[j] for p in v) for j in range(3)],[max(p[j] for p in v) for j in range(3)]]}
spot={'source':'https://github.com/google-deepmind/mujoco_menagerie/tree/'+commit+'/boston_dynamics_spot','commit':commit,'frame':'source (x,y,z) -> browser (x,z,-y), a proper rotation','nodes':nodes,'materials':materials,'meshes':manifest,'bytes':len(blob),'packedSha256':hashlib.sha256(blob).hexdigest(),'collisions':collisions,'home':[0,1.04,-1.8],'footOffset':[0,-.3365,0],'footRadius':.036,'actuator':{'kp':500,'kd':40,'limit':1000,'note':'Published simulation gains/limits, not measured hardware specifications'}}
(out/'definition.mjs').write_text('// Generated by scripts/import-spot.py; source data and licence beside this file.\nexport const SPOT='+json.dumps(spot,separators=(',',':'))+';\n')
for name in ['LICENSE','README.md','spot.xml']:shutil.copyfile(src/name,out/('SOURCE-'+name if name!='LICENSE' else name))
(out/'PROVENANCE.md').write_text('# Spot model provenance\n\nSource: '+spot['source']+'\n\nPinned commit: `'+commit+'`\n\nOriginal OBJ topology, coordinates and vertex normals are retained, converted by the proper rotation `(x,y,z) -> (x,z,-y)` and packed as Float32 positions/normals and Uint32 triangle indices, gzip-compressed. No mesh simplification, proportions edits or procedural replacement shapes. The arm is not imported. See SOURCE-spot.xml and LICENSE.\n\nBrowser physics uses the imported joint transforms/axes/ranges, COMs, masses and inertia tensors with MyDesk’s existing reduced articulated solver. Collision support points are sampled from the original collision hulls; this is not the MuJoCo solver or hardware identification. Motor gains/limits are simulation values.\n')
print('triangles',sum(m['indices']//3 for m in manifest.values()),'bytes',len(blob),'gzip',(out/'meshes.bin.gz').stat().st_size,'mass',sum(n['inertial']['mass'] for n in nodes))
