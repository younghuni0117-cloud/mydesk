import assert from 'node:assert/strict';
import {rewardBreakdown,REWARD_VERSION} from '../robot-rewards.mjs';
import {recoveryStanding} from '../robot-performance.mjs';
import {passedStage} from '../robot-core.mjs';
import {RobotLearner,migrateModel} from '../robot-learning.mjs';
import {visibleMenus,DEFAULT_MENUS,validateMenus} from '../navigation-data.mjs';
const state={dt:1,upright:false,motionQuality:.6,quality:.6,height:.74,angle:0,speed:0,target:0,distance:0,dx:0,impactCost:0,work:0,down:true};
const score=s=>Object.values(rewardBreakdown('recover',{...state,...s})).reduce((a,b)=>a+b,0);
assert.ok(score({})<0,'crouching still is not rewarded');
assert.equal(score({speed:.5}),score({}),'necessary rolling is allowed');
assert.ok(score({recoveryHeightProgress:.2,postureProgress:.1})>0,'getting up earns dense progress');
assert.ok(score({recoveryHeightProgress:-.2})<score({}),'reversing progress costs the same potential');
assert.ok(score({recoveryStable:true,upright:true,motionQuality:1})>0);
assert.equal(rewardBreakdown('recover',{...state,recovered:true,firstRecovery:true}).recovery,30);
assert.equal(rewardBreakdown('recover',{...state,recovered:true,firstRecovery:false}).recovery,0);
const standing={height:.9,angle:0,footDown:true,bodyDown:false,vx:0,vy:0,angularSpeed:0};
assert.equal(recoveryStanding(standing),true);
for(const change of [{footDown:false},{bodyDown:true},{vx:.5},{angularSpeed:2},{angle:.6}])assert.equal(recoveryStanding({...standing,...change}),false);
const outcome={terminationReason:'duration',done:true,time:30,recoveries:1,height:.9,finalUpright:true,recovering:false,stableTime:2};
assert.equal(passedStage(outcome,'recover',30),true);
for(const change of [{finalUpright:false},{recovering:true},{stableTime:.5},{height:.7}])assert.equal(passedStage({...outcome,...change},'recover',30),false);
const learner=new RobotLearner(null,17,{}, {deferEvaluation:true}),saved=learner.snapshot();
saved.rewardVersion=9;saved.attempts=123;saved.taskAttempts.recover=123;saved.algorithmAttempts.ppo=123;
const copy=structuredClone(saved),migrated=migrateModel(saved);
assert.ok(migrated);assert.equal(migrated.rewardVersion,REWARD_VERSION);assert.equal(migrated.evaluationPending,true);
assert.deepEqual(saved,copy,'migration cannot mutate original');
const restored=new RobotLearner(saved,99,{}, {deferEvaluation:true});
assert.equal(restored.attempts,123);assert.deepEqual(restored.weights,saved.weights);assert.deepEqual(restored.mean,saved.mean);assert.deepEqual(restored.taskAttempts,saved.taskAttempts);assert.equal(restored.evaluationPending,true);
const hidden=DEFAULT_MENUS.map(m=>m.id==='career'?{...m,hidden:true}:m);
validateMenus(hidden);assert.ok(!visibleMenus(hidden).some(m=>['career','experienced-jobs'].includes(m.id)));assert.ok(hidden.some(m=>m.id==='experienced-jobs'));
assert.ok(visibleMenus(DEFAULT_MENUS).some(m=>m.id==='career'));
console.log('Recovery rewards, stability, data migration and cascading menu visibility passed');
